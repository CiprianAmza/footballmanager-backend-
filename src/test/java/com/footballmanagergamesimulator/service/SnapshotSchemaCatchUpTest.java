package com.footballmanagergamesimulator.service;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.Statement;
import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.*;

class SnapshotSchemaCatchUpTest {

    @Test
    @DisplayName("""
            GIVEN the current schema has a new table (CLUB_BOARD, unique team) and a new NOT NULL column (TEAM.TIER)
            WHEN an older snapshot without them, whose own constraints already use the same generated names, is
             restored and the catch-up runs
            THEN the table is created with its constraint and the column added with default 0 for the old rows;
             a second run adds nothing
            """)
    void restoredSnapshotGetsTheNewTablesAndColumns() throws Exception {
        try (Connection c = DriverManager.getConnection("jdbc:h2:mem:catchup;DB_CLOSE_DELAY=-1");
             Statement st = c.createStatement()) {
            st.execute("CREATE TABLE TEAM (ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, NAME VARCHAR(255), TIER INTEGER NOT NULL)");
            st.execute("CREATE TABLE CLUB_BOARD (ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, TEAM_ID BIGINT NOT NULL, "
                    + "DIRECTOR_PERSONALITY VARCHAR(255), CONSTRAINT UK_TEAM UNIQUE (TEAM_ID))");
            Map<String, SnapshotSchemaCatchUp.Table> current = SnapshotSchemaCatchUp.capture(st);

            st.execute("DROP ALL OBJECTS");
            st.execute("CREATE TABLE TEAM (ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, NAME VARCHAR(255))");
            st.execute("INSERT INTO TEAM (NAME) VALUES ('Tik Tok')");
            // The old snapshot already uses the names H2 gave the new table's constraints.
            for (String constraint : current.get("CLUB_BOARD").constraints()) {
                java.util.regex.Matcher name = java.util.regex.Pattern.compile("CONSTRAINT \"PUBLIC\"\\.\"([^\"]+)\"").matcher(constraint);
                if (name.find()) st.execute("CREATE TABLE T_" + name.group(1) + " (X INT, CONSTRAINT " + name.group(1) + " UNIQUE (X))");
            }

            List<String> added = SnapshotSchemaCatchUp.apply(st, current);

            assertEquals(List.of("TEAM.TIER", "CLUB_BOARD"), added);
            try (ResultSet rs = st.executeQuery("SELECT TIER FROM TEAM")) {
                assertTrue(rs.next());
                assertEquals(0, rs.getInt(1));
            }
            st.execute("INSERT INTO CLUB_BOARD (TEAM_ID) VALUES (1)");
            assertThrows(Exception.class, () -> st.execute("INSERT INTO CLUB_BOARD (TEAM_ID) VALUES (1)"), "unique kept");
            assertTrue(SnapshotSchemaCatchUp.apply(st, current).isEmpty());
        }
    }

    @Test
    @DisplayName("""
            GIVEN the current schema adds nullable columns whose types end in a parenthesis (VARCHAR(255), TIMESTAMP(6)),
             a NOT NULL NUMERIC(19, 2) column, and a new table with a named unique index
            WHEN an older snapshot without them, which already uses the index's name, is restored and the catch-up runs
            THEN every column is added with its full type, the table is created and its index still enforces uniqueness
            """)
    void columnTypesWithParenthesesAndIndexesSurviveTheCatchUp() throws Exception {
        try (Connection c = DriverManager.getConnection("jdbc:h2:mem:catchup-types;DB_CLOSE_DELAY=-1");
             Statement st = c.createStatement()) {
            st.execute("CREATE TABLE MANAGER_INBOX (ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "ACTION_TYPE VARCHAR(255), FEE NUMERIC(19, 2) NOT NULL, SEEN_AT TIMESTAMP(6))");
            st.execute("CREATE TABLE MANAGER_BACKGROUND (ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "MANAGER_ID BIGINT NOT NULL, LABEL VARCHAR(40))");
            st.execute("CREATE UNIQUE INDEX UX_MANAGER_BACKGROUND_MANAGER ON MANAGER_BACKGROUND (MANAGER_ID)");
            Map<String, SnapshotSchemaCatchUp.Table> current = SnapshotSchemaCatchUp.capture(st);

            st.execute("DROP ALL OBJECTS");
            st.execute("CREATE TABLE MANAGER_INBOX (ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)");
            st.execute("INSERT INTO MANAGER_INBOX (ID) VALUES (1)");
            st.execute("CREATE TABLE OTHER (X INT)");
            st.execute("CREATE INDEX UX_MANAGER_BACKGROUND_MANAGER ON OTHER (X)");

            List<String> added = SnapshotSchemaCatchUp.apply(st, current);

            assertEquals(List.of("MANAGER_INBOX.ACTION_TYPE", "MANAGER_INBOX.FEE", "MANAGER_INBOX.SEEN_AT", "MANAGER_BACKGROUND"), added);
            try (ResultSet rs = st.executeQuery("SELECT COLUMN_NAME, CHARACTER_MAXIMUM_LENGTH, NUMERIC_PRECISION, NUMERIC_SCALE "
                    + "FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'MANAGER_INBOX' AND COLUMN_NAME IN ('ACTION_TYPE', 'FEE') "
                    + "ORDER BY COLUMN_NAME")) {
                assertTrue(rs.next());
                assertEquals("ACTION_TYPE", rs.getString(1));
                assertEquals(255, rs.getInt(2));
                assertTrue(rs.next());
                assertEquals("FEE", rs.getString(1));
                assertEquals(19, rs.getInt(3));
                assertEquals(2, rs.getInt(4));
            }
            st.execute("INSERT INTO MANAGER_BACKGROUND (MANAGER_ID) VALUES (7)");
            assertThrows(Exception.class, () -> st.execute("INSERT INTO MANAGER_BACKGROUND (MANAGER_ID) VALUES (7)"), "unique index kept");
            assertTrue(SnapshotSchemaCatchUp.apply(st, current).isEmpty());
        }
    }

    @Test
    void columnTypeDropsOnlyAParenthesisThatClosesNothing() {
        assertEquals("CHARACTER VARYING(255)", SnapshotSchemaCatchUp.columnType("CHARACTER VARYING(255)"));
        assertEquals("NUMERIC(19, 2) NOT NULL", SnapshotSchemaCatchUp.columnType("NUMERIC(19, 2) NOT NULL"));
        assertEquals("INTEGER", SnapshotSchemaCatchUp.columnType("INTEGER)"));
        assertEquals("TIMESTAMP(6)", SnapshotSchemaCatchUp.columnType("TIMESTAMP(6));"));
    }
}
