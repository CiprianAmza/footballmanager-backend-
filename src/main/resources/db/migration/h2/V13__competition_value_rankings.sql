CREATE TABLE IF NOT EXISTS competition_season_expectation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    season_number INTEGER NOT NULL,
    competition_id BIGINT NOT NULL,
    team_id BIGINT NOT NULL,
    predicted_position INTEGER NOT NULL,
    field_size INTEGER NOT NULL,
    top_eleven_rating DOUBLE PRECISION NOT NULL,
    team_reputation INTEGER NOT NULL,
    competition_prestige DOUBLE PRECISION NOT NULL,
    captured_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_cse_season_comp_team UNIQUE (season_number, competition_id, team_id)
);

CREATE INDEX IF NOT EXISTS idx_cse_season_comp
    ON competition_season_expectation (season_number, competition_id);
CREATE INDEX IF NOT EXISTS idx_cse_team_season
    ON competition_season_expectation (team_id, season_number);
