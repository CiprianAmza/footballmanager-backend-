package com.footballmanagergamesimulator.service.conduct;

import com.footballmanagergamesimulator.model.ConductFine;
import com.footballmanagergamesimulator.model.ConductRule;
import com.footballmanagergamesimulator.model.Human;
import com.footballmanagergamesimulator.model.MatchEvent;
import com.footballmanagergamesimulator.repository.ConductFineRepository;
import com.footballmanagergamesimulator.repository.ConductRuleRepository;
import com.footballmanagergamesimulator.repository.HumanRepository;
import com.footballmanagergamesimulator.service.FinanceService;
import com.footballmanagergamesimulator.util.TypeNames;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.util.*;

/**
 * A club's code of conduct (design DESIGN_START_CARIERA §6.4, decided 2026-11-12). Each offence has a fine in weeks
 * of wages; the code starts at the standard. Raising a fine above the standard upsets the squad once (morale),
 * lowering it does not. When one of the club's players is booked, the fine is taken from his wages and paid to
 * the club, once per card.
 */
@Service
public class ConductService {

    /** Fines the manager may choose, in weeks of wages. */
    public static final List<Double> ALLOWED_WEEKS = List.of(0.0, 0.5, 1.0, 2.0, 3.0, 4.0);
    /** Morale lost by every player per half-week a fine goes above the standard (implicit, to tune in testing). */
    public static final double MORALE_PER_HALF_WEEK = 2.0;
    public static final double MAX_MORALE_DROP = 10.0;

    public enum Offence {
        YELLOW_CARD("Yellow card", 0.0, "yellow_card"),
        RED_CARD("Red card", 1.0, "red_card"),
        /** Not generated by the game yet; the rule waits for the event. */
        MISSED_TRAINING("Missed training", 1.0, null);

        private final String label;
        private final double standardWeeks;
        private final String eventType;

        Offence(String label, double standardWeeks, String eventType) {
            this.label = label;
            this.standardWeeks = standardWeeks;
            this.eventType = eventType;
        }

        public String label() { return label; }
        public double standardWeeks() { return standardWeeks; }

        static Optional<Offence> forEvent(String eventType) {
            return Arrays.stream(values()).filter(o -> Objects.equals(o.eventType, eventType)).findFirst();
        }
    }

    public record Line(String offence, String label, double standardWeeks, double fineWeeks, boolean active) {}

    public record Update(List<Line> code, double moraleDrop) {}

    private final ConductRuleRepository ruleRepository;
    private final ConductFineRepository fineRepository;
    private final HumanRepository humanRepository;
    private final FinanceService financeService;

    public ConductService(ConductRuleRepository ruleRepository, ConductFineRepository fineRepository,
                          HumanRepository humanRepository, FinanceService financeService) {
        this.ruleRepository = ruleRepository;
        this.fineRepository = fineRepository;
        this.humanRepository = humanRepository;
        this.financeService = financeService;
    }

    /** The club's code: every offence, its standard and the fine in force. */
    public List<Line> code(long teamId) {
        Map<String, Double> chosen = new HashMap<>();
        ruleRepository.findAllByTeamId(teamId).forEach(r -> chosen.put(r.getOffence(), r.getFineWeeks()));
        List<Line> lines = new ArrayList<>();
        for (Offence offence : Offence.values()) {
            lines.add(new Line(offence.name(), offence.label(), offence.standardWeeks(),
                    chosen.getOrDefault(offence.name(), offence.standardWeeks()), offence.eventType != null));
        }
        return lines;
    }

    public double fineWeeks(long teamId, Offence offence) {
        return code(teamId).stream().filter(l -> l.offence().equals(offence.name()))
                .mapToDouble(Line::fineWeeks).findFirst().orElse(offence.standardWeeks());
    }

    /**
     * Sets fines. The squad reacts only to the part of a raise above both the standard and the fine already in
     * force: every player loses {@link #MORALE_PER_HALF_WEEK} morale per half-week, at most {@link #MAX_MORALE_DROP}.
     */
    @Transactional
    public Update update(long teamId, Map<String, Double> fines) {
        Map<String, ConductRule> rules = new HashMap<>();
        ruleRepository.findAllByTeamId(teamId).forEach(r -> rules.put(r.getOffence(), r));
        double halfWeeksAbove = 0;
        for (Map.Entry<String, Double> entry : fines.entrySet()) {
            Offence offence = Offence.valueOf(entry.getKey());
            double weeks = entry.getValue() == null ? offence.standardWeeks() : entry.getValue();
            if (!ALLOWED_WEEKS.contains(weeks)) {
                throw new IllegalArgumentException("A fine is 0, 0.5, 1, 2, 3 or 4 weeks of wages.");
            }
            ConductRule rule = rules.computeIfAbsent(offence.name(), name -> {
                ConductRule r = new ConductRule();
                r.setTeamId(teamId);
                r.setOffence(name);
                r.setFineWeeks(offence.standardWeeks());
                return r;
            });
            double floor = Math.max(offence.standardWeeks(), rule.getFineWeeks());
            if (weeks > floor) halfWeeksAbove += (weeks - floor) / 0.5;
            rule.setFineWeeks(weeks);
        }
        ruleRepository.saveAll(rules.values());
        double drop = Math.min(MAX_MORALE_DROP, halfWeeksAbove * MORALE_PER_HALF_WEEK);
        if (drop > 0) {
            List<Human> squad = humanRepository.findAllByTeamIdAndTypeId(teamId, TypeNames.PLAYER_TYPE);
            for (Human player : squad) {
                if (player.isRetired()) continue;
                player.setMorale(Math.max(0, player.getMorale() - drop));
            }
            humanRepository.saveAll(squad);
        }
        return new Update(code(teamId), drop);
    }

    /** A card for a player of {@code teamId}: his fine goes to the club, once per card. Returns the amount. */
    @Transactional
    public long fine(MatchEvent card, long teamId, int season, int day) {
        Optional<Offence> offence = Offence.forEvent(card.getEventType());
        if (offence.isEmpty() || card.getId() <= 0 || fineRepository.existsByMatchEventId(card.getId())) return 0;
        double weeks = fineWeeks(teamId, offence.get());
        if (weeks <= 0) return 0;
        Human player = humanRepository.findById(card.getPlayerId()).orElse(null);
        if (player == null) return 0;
        long amount = Math.round(player.getWage() * 12.0 / 52.0 * weeks);
        if (amount <= 0) return 0;
        financeService.recordTransaction(teamId, season, day, "FINE",
                offence.get().label() + " fine: " + player.getName(), amount);
        ConductFine row = new ConductFine();
        row.setTeamId(teamId);
        row.setPlayerId(player.getId());
        row.setPlayerName(player.getName());
        row.setMatchEventId(card.getId());
        row.setOffence(offence.get().name());
        row.setFineWeeks(weeks);
        row.setAmount(amount);
        row.setSeason(season);
        fineRepository.save(row);
        return amount;
    }
}
